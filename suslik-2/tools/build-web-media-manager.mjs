import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const core=await readFile(new URL('media-manager-web/core.js',root),'utf8');
const app=await readFile(new URL('media-manager-web/app.js',root),'utf8');
const slots=await readFile(new URL('content/media-manager-slots.json',root),'utf8');
const bundle='/* Generated by tools/build-web-media-manager.mjs. */\n'+
 core.replace(/^export /gm,'')+'\n'+app.replace(/^import .*;\r?\n/,'');
await writeFile(new URL('media-manager-web/app-bundle.js',root),bundle);
await writeFile(new URL('media-manager-web/slots.json',root),slots);
